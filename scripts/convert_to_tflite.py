"""
convert_to_tflite.py
====================
Converts a PyTorch (via ONNX) weather classification model to TensorFlow Lite
format with optional quantization for mobile deployment.
"""

import argparse
import logging
import os
from pathlib import Path
import shutil
import sys

# Подавление конфликта Keras 3 и информационных логов OneDNN
os.environ["TF_USE_LEGACY_KERAS"] = "1"
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"

logging.basicConfig(
    level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s"
)
logger = logging.getLogger(__name__)

BASE_DIR = Path(__file__).resolve().parent.parent
DEFAULT_ONNX = BASE_DIR / "models" / "weather_model.onnx"
DEFAULT_OUTPUT_DIR = BASE_DIR / "models"


def parse_args():
    parser = argparse.ArgumentParser(
        description="Convert weather model to TFLite format."
    )
    parser.add_argument(
        "--onnx",
        type=str,
        default=str(DEFAULT_ONNX),
        help="Path to the ONNX model file",
    )
    parser.add_argument(
        "--quantize",
        type=str,
        default="fp16",
        choices=["fp16", "int8", "none"],
        help="Quantization mode: fp16 (default), int8, or none",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Target .tflite output file path",
    )
    parser.add_argument(
        "--calibration_dir",
        type=str,
        default=None,
        help="Directory with numpy (.npy) tensors for INT8 calibration",
    )
    return parser.parse_args()


def convert_model(
    onnx_path: Path,
    output_path: Path,
    quantize: str,
    calibration_dir: str = None,
) -> None:
    try:
        import onnx2tf
        import tensorflow as tf
    except ImportError:
        raise ImportError(
            "onnx2tf and tensorflow are required. Run: pip install onnx2tf tensorflow"
        )

    logger.info("=== Starting conversion ===")
    logger.info(f"Input ONNX:    {onnx_path}")
    logger.info(f"Target TFLite: {output_path}")
    logger.info(f"Quantization:  {quantize}")

    work_dir = output_path.parent / "_onnx2tf_temp"
    if work_dir.exists():
        shutil.rmtree(work_dir)
    work_dir.mkdir(parents=True, exist_ok=True)

    try:
        # 1. Экспорт ONNX -> SavedModel через onnx2tf
        conversion_args = {
            "input_onnx_file_path": str(onnx_path),
            "output_folder_path": str(work_dir),
            "non_verbose": True,
        }

        if quantize == "int8":
            conversion_args["output_integer_quantized_tflite"] = True
            if calibration_dir:
                conversion_args["custom_input_op_name_np_data_path"] = (
                    calibration_dir
                )
            else:
                conversion_args["output_dynamic_range_quantized_tflite"] = True

        onnx2tf.convert(**conversion_args)

        # 2. Формирование целевого .tflite файла
        stem = onnx_path.stem

        if quantize == "fp16":
            # Честный FP16 через TFLiteConverter поверх созданного SavedModel
            logger.info("Applying FP16 quantization via TFLiteConverter...")
            converter = tf.lite.TFLiteConverter.from_saved_model(str(work_dir))
            converter.optimizations = [tf.lite.Optimize.DEFAULT]
            converter.target_spec.supported_types = [tf.float16]
            tflite_model = converter.convert()
            output_path.write_bytes(tflite_model)

        elif quantize == "int8":
            # Берем сгенерированный onnx2tf квантованный файл
            int8_candidates = [
                work_dir / f"{stem}_integer_quant.tflite",
                work_dir / f"{stem}_dynamic_range_quant.tflite",
            ]
            found = False
            for cand in int8_candidates:
                if cand.exists():
                    shutil.copy2(cand, output_path)
                    found = True
                    break
            if not found:
                raise RuntimeError(
                    "INT8 TFLite model was not generated by onnx2tf."
                )

        else:
            # Full Precision (Float32)
            f32_cand = work_dir / f"{stem}_float32.tflite"
            if f32_cand.exists():
                shutil.copy2(f32_cand, output_path)
            else:
                converter = tf.lite.TFLiteConverter.from_saved_model(
                    str(work_dir)
                )
                output_path.write_bytes(converter.convert())

        logger.info(f"Model successfully saved to: {output_path}")

    finally:
        if work_dir.exists():
            shutil.rmtree(work_dir, ignore_errors=True)


def main():
    args = parse_args()
    onnx_path = Path(args.onnx).resolve()

    if not onnx_path.exists():
        logger.error(f"ONNX model file not found: {onnx_path}")
        sys.exit(1)

    if args.output:
        output_path = Path(args.output).resolve()
    else:
        suffix = f"_{args.quantize}" if args.quantize != "none" else ""
        output_path = (
            DEFAULT_OUTPUT_DIR / f"{onnx_path.stem}{suffix}.tflite"
        ).resolve()

    output_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        convert_model(
            onnx_path, output_path, args.quantize, args.calibration_dir
        )
    except Exception as exc:
        logger.error(f"Conversion failed: {exc}")
        sys.exit(1)

    if output_path.exists():
        size_mb = output_path.stat().st_size / (1024 * 1024)
        logger.info("=" * 60)
        logger.info(f"Output model: {output_path.name}")
        logger.info(f"Output size:  {size_mb:.2f} MB")
        logger.info("=" * 60)


if __name__ == "__main__":
    main()